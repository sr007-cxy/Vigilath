// User role management (admin-only) — /api/admin/users
// List / create account / change role / set membership / reset password, plus the three data sets the detail drawer needs:
// user details, payment records, audit records (the latter two server-paginated).
import { readApiError, localizedHeaders } from './apiError';

export interface AdminUserItem {
  id: number;
  email: string;
  name?: string | null;
  role: string;                 // Includes agency roles; agency roles are shown read-only and maintained via the organization member API
  is_active: boolean;
  tenant_id?: number | null;    // Bound gateway tenant
  tenant_name?: string | null;
  membership_id?: number | null;        // No paid record = null (free tier)
  membership_name?: string | null;
  membership_end_date?: string | null;
}

async function request<T>(method: string, path: string, token: string, body?: unknown): Promise<T> {
  const init: RequestInit = {
    method,
    headers: localizedHeaders({
      Authorization: `Bearer ${token}`,
      ...(body !== undefined ? { 'Content-Type': 'application/json' } : {}),
    }),
  };
  if (body !== undefined) init.body = JSON.stringify(body);
  const resp = await fetch(`/api/admin/users${path}`, init);
  if (!resp.ok) {
    throw new Error(await readApiError(resp, `Request ${method} ${path} failed`));
  }
  return resp.json() as Promise<T>;
}

export interface UserBalanceInfo {
  balance_cents: number;
  granted_cents: number;
  recharged_cents: number;
  spent_cents: number;
  available: boolean;     // false = the balance table couldn't be read; show "Temporarily unavailable" rather than 0
}

export interface AdminUserDetail extends AdminUserItem {
  phone?: string | null;
  phone_verified_at?: string | null;
  wechat_nickname?: string | null;
  wechat_avatar?: string | null;
  wechat_bound: boolean;
  wechat_subscribed: boolean;
  created_at?: string | null;          // null for existing accounts registered before 2026-08-26
  membership_start_date?: string | null;
  balance: UserBalanceInfo;
  detection_count: number;
  detection_last_at?: string | null;
  payment_count: number;
  payment_paid_count: number;
  payment_paid_cents: Record<string, number>;   // Currency -> total paid (cents), not merged
  payment_last_paid_at?: string | null;
}

export interface AdminPaymentItem {
  id: number;
  purpose: string;                     // membership | topup
  membership_slug?: string | null;
  membership_name?: string | null;
  amount_cents: number;
  currency: string;
  status: string;                      // pending | paid | expired | canceled
  provider: string;                    // stripe | wechat | moltspay
  tx_hash?: string | null;
  created_at?: string | null;
  completed_at?: string | null;
}

export interface AdminDetectionItem {
  id: number;
  url: string;
  score?: number | null;
  grade?: string | null;
  tier?: string | null;
  mode: string;                        // free | advanced
  created_at?: string | null;
  deleted_at?: string | null;          // Records deleted by the user, still listed in the admin
}

export interface Paged<T> {
  items: T[];
  total: number;
  page: number;
  size: number;
}

export interface CreateUserPayload {
  email: string;
  name?: string | null;
  role: string;
  password?: string | null;   // Leave empty -> randomly generated by the server
}

export type AdminCreditKind = 'recharge' | 'grant';

export interface AdminCreditResult {
  status: string;
  balance_cents: number;
  amount_cents: number;
  idem_key: string;
  duplicate: boolean;
}

export const adminUsersApi = {
  async list(token: string, search?: string): Promise<AdminUserItem[]> {
    const q = search && search.trim() ? `?search=${encodeURIComponent(search.trim())}` : '';
    return request('GET', q, token);
  },
  // Create user: the initial plain-text password is echoed only once (randomly generated by the server if left empty)
  async create(
    payload: CreateUserPayload, token: string,
  ): Promise<{ user: AdminUserItem; initial_password: string }> {
    return request('POST', '', token, payload);
  },
  // Detail drawer: profile + membership + balance + payment/audit summary
  async detail(userId: number, token: string): Promise<AdminUserDetail> {
    return request('GET', `/${userId}`, token);
  },
  async payments(
    userId: number, token: string, page = 1, size = 10,
  ): Promise<Paged<AdminPaymentItem>> {
    return request('GET', `/${userId}/payments?page=${page}&size=${size}`, token);
  },
  async detections(
    userId: number, token: string, page = 1, size = 10,
  ): Promise<Paged<AdminDetectionItem>> {
    return request('GET', `/${userId}/detections?page=${page}&size=${size}`, token);
  },
  // Manual credit entries go through the balance center's admin endpoint; recharge / grant accumulate into top-ups / gifts respectively.
  async creditBalance(
    userId: number,
    amount: number,
    kind: AdminCreditKind,
    reason: string,
    token: string,
  ): Promise<AdminCreditResult> {
    const idemKey = `admin_${kind}_${userId}_${Date.now()}_${crypto.randomUUID()}`;
    const resp = await fetch('/api/admin/balance/credit', {
      method: 'POST',
      headers: localizedHeaders({
        Authorization: `Bearer ${token}`,
        'Content-Type': 'application/json',
      }),
      body: JSON.stringify({
        user_id: userId,
        amount_cents: amount,
        kind,
        reason,
        idem_key: idemKey,
      }),
    });
    if (!resp.ok) {
      throw new Error(await readApiError(resp, '积分入账失败'));
    }
    return resp.json() as Promise<AdminCreditResult>;
  },
  async updateRole(userId: number, role: string, token: string): Promise<AdminUserItem> {
    return request('PATCH', `/${userId}/role`, token, { role });
  },
  // Set membership tier: free tier = cancel paid membership; paid tiers get a validity period by cycle, setting the same tier again extends it
  async updateMembership(userId: number, membershipId: number, token: string): Promise<AdminUserItem> {
    return request('PATCH', `/${userId}/membership`, token, { membership_id: membershipId });
  },
  // Reset password: without newPassword the server generates a random one; the plain text is echoed only once
  async resetPassword(
    userId: number, token: string, newPassword?: string,
  ): Promise<{ id: number; email: string; new_password: string }> {
    return request('POST', `/${userId}/reset-password`, token, { new_password: newPassword || null });
  },
};
