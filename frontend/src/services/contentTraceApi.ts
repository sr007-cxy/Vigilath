// Generation provenance API -- reverse-lookup entry for implicit labels under the "Measures for Labeling AI-Generated Synthetic Content".
// Backend geo/api/content_trace.py, mounted at /api/admin/content-trace, guarded by require_workbench.
// See the page pages/Admin/ContentTrace.tsx (route /ops/content-trace).

import { localizedHeaders, readApiError } from './apiError';

const API_BASE = (import.meta.env.VITE_API_URL as string) || '/api';

export type TraceKind = 'text' | 'image';

/** A generation provenance record -- the "generator + IP + time + model + content ID" the filing materials require.
 *  Text drafts (ID VGL-...) and AI images (ID VGI-...) share this structure, distinguished by kind. */
export interface ContentTrace {
  kind: TraceKind;
  trace_no?: string | null;
  doc_id: number;
  title: string;
  status: string;
  /** 'ai' = generated/synthesized by this platform; 'user' = client-supplied draft (no AI label, but provenance is registered all the same) */
  source: string;
  generated_at?: string | null;
  updated_at?: string | null;
  llm_model: string;
  gen_user_id?: number | null;
  gen_user_email: string;
  /** 'system' = automatic batch run, not manually triggered */
  gen_client_ip: string;
  topic_id: number;
  topic_name: string;
  owner_user_id?: number | null;
  owner_email: string;
  /** Whether the explicit label line is still in the body */
  has_explicit_mark: boolean;
  /** Whether the zero-width watermark is still in the body (images: whether EXIF/tEXt metadata can be read back with a matching ID) */
  has_implicit_mark: boolean;
  /** Character count for text; file byte size for images */
  body_chars: number;
  // ─── kind='image' only ───
  media_id?: number | null;
  /** Public preview URL; open it to see the watermark in the bottom-right corner directly */
  media_url?: string;
  media_filename?: string;
  /** Metadata read back from the image file (ContentProducer / ContentTraceNo / ...) */
  media_meta?: Record<string, string>;
}

export interface TraceList {
  total: number;
  items: ContentTrace[];
  /** Existing drafts generated before the feature launched lack the three provenance columns; the page must say so, not read it as "missed collection" */
  untraced: number;
}

export interface ExtractResult {
  trace_no?: string | null;
  found: boolean;
  record?: ContentTrace | null;
  message: string;
}

async function request<T>(
  method: string, path: string, token: string, body?: unknown,
): Promise<T> {
  const init: RequestInit = {
    method,
    headers: localizedHeaders({
      Authorization: `Bearer ${token}`,
      ...(body !== undefined ? { 'Content-Type': 'application/json' } : {}),
    }),
  };
  if (body !== undefined) init.body = JSON.stringify(body);
  const resp = await fetch(`${API_BASE}/admin/content-trace${path}`, init);
  if (!resp.ok) {
    const msg = await readApiError(resp, `Request ${method} ${path} failed`);
    throw new Error(msg);
  }
  return resp.json() as Promise<T>;
}

export const contentTraceApi = {
  /** Ledger list -- the latest 50 by default, ordered by generation time descending. kind: text (default) / image / all */
  list(token: string, opts: { topicId?: number; q?: string; limit?: number;
                              kind?: 'text' | 'image' | 'all' } = {}) {
    const qs = new URLSearchParams();
    if (opts.topicId) qs.set('topic_id', String(opts.topicId));
    if (opts.q) qs.set('q', opts.q);
    if (opts.kind) qs.set('kind', opts.kind);
    if (opts.limit) qs.set('limit', String(opts.limit));
    const s = qs.toString();
    return request<TraceList>('GET', s ? `?${s}` : '', token);
  },

  /** Reverse lookup by content ID; when the ID doesn't exist the backend returns 404 (the conclusion being "not generated by this platform") */
  get(traceNo: string, token: string) {
    return request<ContentTrace>('GET', `/${encodeURIComponent(traceNo)}`, token);
  },

  /** Paste body -> decode the zero-width watermark -> look up the ledger (verification entry for reposted content) */
  extract(text: string, token: string) {
    return request<ExtractResult>('POST', '/extract', token, { text });
  },
};
