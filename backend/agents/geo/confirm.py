"""Two-step confirmation — "preview first, execute next turn" tickets for irreversible / money-spending actions.

**Why not a bool parameter**: the agent runs with end_strategy="exhaustive" (agent.py:140,
fixing DeepSeek skipping tools when it emits text+tool_call in one response), so the framework runs every tool_call in a response.
DeepSeek routinely emits two tool_calls in one response — if confirmation were a bool, the model could
"preview once -> immediately call again with confirm=True", making two-step confirmation worthless.

So the confirmation parameter is an HMAC ticket bound to (account_id, locked_topic_id, tool, args fingerprint, turn_id, exp).
Four gates, the first three are mechanism-level (independent of the prompt):

  1. token is HMAC, not bool      — the model can't make one up
  2. turn binding (SAME_TURN)     — rejected if the ticket's turn == this turn. deps.turn_id is generated by api.py
                                    as a uuid4 per HTTP request -> it can differ only if **a new user message really
                                    came in**. This is the pivot of the whole design.
  3. args fingerprint binding     — "preview 3 articles, confirm 30", swapping doc_id, changing force all invalidate it
  4. negation veto (DECLINED)     — user says 「算了」 ("never mind") next turn but the model still executes with the token

Failures always **return a structured dict, never raise ModelRetry** — retries=2 would tempt the model to guess the token twice.

This module is pure functions (no DB, no network); eval/test_confirm.py can cover it 100%.
"""
from __future__ import annotations

import hashlib
import hmac
import json
import os
import time

from agents.geo.deps import AgentDeps

_VERSION = "v1"


def _ttl() -> int:
    try:
        return max(60, int(os.environ.get("AGENT_CONFIRM_TTL", "900")))
    except (TypeError, ValueError):
        return 900


def _secret() -> str:
    """Reuse the main backend's SECRET_KEY (agent and main backend share one config)."""
    from geo.database import settings

    return str(getattr(settings, "SECRET_KEY", "") or "")


class ConfirmError(Exception):
    def __init__(self, code: str, message: str):
        super().__init__(message)
        self.code = code
        self.message = message


def _digest(args: dict | None) -> str:
    """Args fingerprint. Excludes token-type fields themselves, canonical JSON, first 16 chars of sha256."""
    clean = {
        k: v for k, v in (args or {}).items()
        if k not in ("confirm_token", "rwj_confirm_token")
    }
    blob = json.dumps(clean, ensure_ascii=False, sort_keys=True, default=str)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()[:16]


def _sig(deps: AgentDeps, tool: str, args_digest: str, turn: str, exp: int) -> str:
    msg = (
        f"agent-confirm|{deps.account_id}|{deps.locked_topic_id}|{tool}"
        f"|{args_digest}|{turn}|{exp}"
    ).encode("utf-8")
    return hmac.new(_secret().encode("utf-8"), msg, hashlib.sha256).hexdigest()


def issue(deps: AgentDeps, *, tool: str, args: dict | None) -> tuple[str, int]:
    """Issue a ticket. Format v1.{exp}.{turn}.{sig} (rwj_channel's {exp}.{sig} style plus two segments)."""
    ttl = _ttl()
    exp = int(time.time()) + ttl
    turn = deps.turn_id or "-"
    sig = _sig(deps, tool, _digest(args), turn, exp)
    return f"{_VERSION}.{exp}.{turn}.{sig}", ttl


def verify(deps: AgentDeps, token: str, *, tool: str, args: dict | None) -> None:
    """Verify a ticket. Raise ConfirmError if any check fails."""
    parts = str(token or "").split(".")
    if len(parts) != 4 or parts[0] != _VERSION:
        raise ConfirmError("BAD_TOKEN", "确认令牌格式不对。请重新走一次预览拿到新的令牌,不要自己编造。")
    _, exp_s, turn, sig = parts
    try:
        exp = int(exp_s)
    except (TypeError, ValueError):
        raise ConfirmError("BAD_TOKEN", "确认令牌格式不对。请重新走一次预览拿到新的令牌。") from None

    expect = _sig(deps, tool, _digest(args), turn, exp)
    if not hmac.compare_digest(sig, expect):
        # Wrong tool / wrong project / wrong account / changed args all end up here
        raise ConfirmError(
            "BAD_TOKEN",
            "确认令牌与本次调用对不上(工具、项目或参数变了)。"
            "请用**完全相同的参数**重新预览一次,把新的预览转述给用户再确认。",
        )
    if exp < int(time.time()):
        raise ConfirmError("TOKEN_EXPIRED", "确认令牌已超时。")
    # ★ Pivot: self-confirmation in the same turn — the ticket's issuing turn equals this turn, meaning no new user message in between
    if turn and deps.turn_id and turn == deps.turn_id:
        raise ConfirmError(
            "SAME_TURN",
            "还没有得到用户确认。请先把上一步的预览如实转述给用户、等他回复,"
            "**不要在同一轮里自己确认**。",
        )


# Negative-intent blocklist. Blocklist rather than allowlist: Chinese affirmatives are too varied (「行」「可以」「嗯」「就这样」 ("ok", "sure", "mm", "that's it")),
# an allowlist would block real confirmations; negations are concentrated, and misses are covered by turn/args binding and prompt constraints.
_DECLINE_WORDS = (
    "不用了", "不用", "算了", "取消", "先别", "别发", "别弄", "不要", "不发", "不行",
    "等等", "等一下", "再想想", "再看看", "先不", "暂时不", "停一下", "撤销", "放弃",
    "no", "cancel", "stop", "abort",
)


def user_declined(text: str) -> bool:
    """True if this turn's user message has explicit negative intent."""
    t = (text or "").strip().lower()
    if not t:
        return False
    return any(w in t for w in _DECLINE_WORDS)


def needs_confirm(deps: AgentDeps, *, tool: str, action_label: str, args: dict | None,
                  preview: dict, impact: list[str],
                  irreversible: list[str] | None = None,
                  cost: dict | None = None,
                  topic=None, note: str = "") -> dict:
    """Build the preview return body. **This function never performs any write.**"""
    token, ttl = issue(deps, tool=tool, args=args)
    out = {
        "needs_confirm": True,
        "modified": False,            # Always False, following _sales_gate's signal style
        "action": tool,
        "action_label": action_label,
        "preview": preview,
        "impact": impact,
        "irreversible": irreversible or [],
        "cost": cost,
        "confirm_token": token,
        "expires_in": ttl,
        "how_to_confirm": (
            "把上面的 preview / impact / irreversible / cost 如实、逐条转述给用户,"
            "问他是否确认执行,然后**结束本轮**。用户在**下一条消息**里明确确认后,"
            "再用完全相同的参数 + 本 confirm_token 调一次本工具。"
            "绝不在同一轮里自己确认,绝不编造令牌。"
        ),
    }
    if topic is not None:
        out["topic"] = {"id": topic.id, "name": topic.name}
    if note:
        out["_note"] = note
    return out


def guard(deps: AgentDeps, token: str, *, tool: str, args: dict | None,
          rebuild_preview=None) -> dict | None:
    """One-line gate inside tools.

    Returns None  = check passed, may execute;
    Returns dict  = return it directly to the model (one of preview / failure / cancelled).

    rebuild_preview: optional zero-arg callback; on expiry it produces a **fresh preview** (with a new token).
    Replying "token expired" would deadlock the conversation; auto re-issuing is the right thing.
    """
    # The user explicitly said no this turn — takes priority over token validation (the token may be valid, but the person changed their mind)
    if user_declined(deps.user_message):
        return {
            "ok": False, "modified": False, "cancelled": True,
            "message": "用户这一轮的回复不是确认,已取消本次操作,数据一个字都没改。",
        }
    try:
        verify(deps, token, tool=tool, args=args)
    except ConfirmError as e:
        if e.code == "TOKEN_EXPIRED" and callable(rebuild_preview):
            fresh = rebuild_preview()
            if isinstance(fresh, dict):
                fresh["_note"] = "上一次确认已超时,以下是最新的预览,请再向用户确认一次。"
                return fresh
        return {"ok": False, "modified": False, "code": e.code, "message": e.message}
    return None
