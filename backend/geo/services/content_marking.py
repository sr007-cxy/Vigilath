"""Content labeling and generation provenance -- implementation layer for the "Measures for Labeling AI-Generated Synthetic Content".

Corresponds to items 5 (implicit text labeling) and 6 (explicit text labeling) of the algorithm filing correction list;
plan in `docs/09-软著与专利/备案补正/02-方案与代办台账.md` sections 4.1 / 4.2.

Three things, all contained in this module; do not reimplement them at each call site:

1. **Explicit label** -- ⚠️ since 2026-08-17 **no longer written into the body**. Drafts are automatically posted to external media by publish channels
   (aitoearn own accounts / Ruanwenjiang / Meijieku / Mediumsly), and a body line
   "内容由AI生成…生成方 …" ("AI-generated content... generated by ...") would be published by the platform along with the copy. The explicit label is now
   **shown only in the product UI** (AiDisclosureBar in `frontend/.../ContentReview.tsx`);
   the "Labeling Measures" require a notice "on the display interface of generated content", which this covers.
   `disclosure_line()` / `apply_marks()` are kept but have no callers by default.
2. **Implicit label / provenance** -- the DB stores three columns `gen_user_id` / `gen_client_ip` /
   `gen_trace_no`, forming a ledger of "generator + IP + time + model + content id",
   the **single source of truth** for provenance. The zero-width character watermark (`encode_watermark`) is likewise no longer written
   into the body since 2026-08-17 -- it would stick to third-party platforms with the body, amounting to hidden marks in external content.
3. **Trigger source context** -- generation runs in a background thread (`schedule_generation` -> `spawn_thread`),
   and the request object is long gone. The API layer uses `gen_origin()` to put the trigger user / client IP into a contextvar;
   `spawn_thread` carries the contextvar snapshot into the thread, and it is read back when persisting.
   Automated batch runs (cron / siyuan_tick) have no request, so IP is recorded as `SYSTEM_IP` and the owner falls back to the topic owner.

Content ids look like `VGL-CXSY-20260816-000123`:
`VGL` fixed prefix + filing entity code + generation date (Beijing time) + six-digit doc.id.
Uses doc.id rather than a per-day counter -- naturally unique, no locks under concurrency, and regeneration keeps the id.
"""
from __future__ import annotations

import contextvars
import logging
import os
import re
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import datetime, timedelta
from typing import Iterator, Optional

log = logging.getLogger(__name__)

# --------------------------- Filing entity metric definition ---------------------------
# Consistent with the entity info in `docs/09-软著与专利/备案补正/00-总览.md`; changing this changes all label copy.
SUBJECT_CODE = os.environ.get("GEO_TRACE_SUBJECT_CODE", "CXSY").strip() or "CXSY"
SUBJECT_NAME = os.environ.get(
    "GEO_TRACE_SUBJECT_NAME", "<company-name>").strip()

# Explicit label text -- "内容由AI生成" ("AI-generated content") is the match string of the mandatory disclaimer in the compliance lexicon; do not change these seven characters
DISCLOSURE_TEXT = "内容由AI生成,仅供参考"

# IP placeholder recorded for automated batch runs (no HTTP request); the provenance page uses it to tell "manually triggered / automated batch run"
SYSTEM_IP = "system"

TRACE_NO_RE = re.compile(r"VGL-[A-Z0-9]{2,12}-\d{8}-\d{6}")

# Explicit label block: optional blank line + optional `---` separator + the whole `> 内容由AI生成…` ("AI-generated content...") line
_DISCLOSURE_BLOCK_RE = re.compile(
    r"\n*(?:-{3,}\s*\n+)?>[ \t]*" + re.escape("内容由AI生成") + r"[^\n]*")

# --------------------------- Zero-width watermark character table ---------------------------
# U+2060 WORD JOINER as start/end sentinel, U+200B / U+200C carry 0 / 1.
# None of the three break lines, take width or affect layout; they survive rich text editors and WeChat/official account pasting.
# Always written as escape codes -- typed directly in source these characters are invisible, and breaking them would go unnoticed.
_ZW_START = chr(0x2060)   # WORD JOINER -- start/end sentinel
_ZW_END = chr(0x2060)
_ZW_0 = chr(0x200B)       # ZERO WIDTH SPACE      → bit 0
_ZW_1 = chr(0x200C)       # ZERO WIDTH NON-JOINER → bit 1
_ZW_BLOCK_RE = re.compile("[" + _ZW_START + _ZW_0 + _ZW_1 + "]{4,}")


# --------------------------- Trigger source context ---------------------------
@dataclass(frozen=True)
class GenOrigin:
    """Trigger source of one generation. Empty user_id means unknown (falls back to the topic owner when persisting)."""
    user_id: Optional[int] = None
    client_ip: str = ""


_origin: contextvars.ContextVar[GenOrigin] = contextvars.ContextVar(
    "gen_origin", default=GenOrigin())


@contextmanager
def gen_origin(*, user_id: Optional[int] = None,
               client_ip: str = "") -> Iterator[GenOrigin]:
    """Wrap generation-triggering calls in the API layer, passing the trigger user and client IP to the background thread.

    Usage (see api/content.py, api/admin_review.py):

        with gen_origin(user_id=current_user.id, client_ip=client_ip(request)):
            schedule_generation(topic_id=t.id)

    `schedule_generation` internally uses `spawn_thread` (with a contextvars snapshot),
    so this context reaches persistence points that run tens of seconds later.
    """
    new = GenOrigin(user_id=user_id, client_ip=(client_ip or "").strip()[:64])
    token = _origin.set(new)
    try:
        yield new
    finally:
        _origin.reset(token)


def current_origin() -> GenOrigin:
    return _origin.get()


def client_ip(request) -> str:
    """Get the real client IP from the request.

    Production runs behind an nginx reverse proxy, so `request.client.host` is always 127.0.0.1; we must read
    the **first hop** of X-Forwarded-For (later entries in the chain are the proxies themselves).
    """
    if request is None:
        return ""
    try:
        xff = (request.headers.get("x-forwarded-for") or "").strip()
        if xff:
            return xff.split(",")[0].strip()[:64]
        real = (request.headers.get("x-real-ip") or "").strip()
        if real:
            return real[:64]
        return (getattr(getattr(request, "client", None), "host", "") or "")[:64]
    except Exception:  # noqa: BLE001 -- getting the IP must never crash the generation request
        return ""


# --------------------------- Content id ---------------------------
def make_trace_no(doc_id: int, created_at: Optional[datetime] = None) -> str:
    """`VGL-<entity code>-<yyyymmdd>-<six-digit doc.id>`.

    created_at is naive UTC (ORM default `datetime.utcnow`); the date in the id uses Beijing time,
    the same metric definition as page display and the dates reported in the "correction statement".
    """
    base = created_at or datetime.utcnow()
    day = (base + timedelta(hours=8)).strftime("%Y%m%d")
    return f"VGL-{SUBJECT_CODE}-{day}-{int(doc_id):06d}"


# --------------------------- Zero-width watermark ---------------------------
def encode_watermark(trace_no: str) -> str:
    """Content id -> zero-width string. The id is ASCII, 8 bits per character."""
    bits = "".join(format(b, "08b") for b in trace_no.encode("ascii", "ignore"))
    return _ZW_START + "".join(_ZW_1 if b == "1" else _ZW_0 for b in bits) + _ZW_END


def extract_trace_no(text: str) -> Optional[str]:
    """Decode the content id from the body -- read the zero-width watermark first, falling back to the plaintext id.

    Reposters usually copy only the body, which carries the zero-width characters along; if they stripped zero-width characters,
    the plaintext id in the explicit label line provides another fallback.
    """
    if not text:
        return None
    for block in _ZW_BLOCK_RE.findall(text):
        body = block.strip(_ZW_START)
        bits = "".join("1" if ch == _ZW_1 else "0" for ch in body
                       if ch in (_ZW_0, _ZW_1))
        if len(bits) < 8:
            continue
        raw = bytes(int(bits[i:i + 8], 2) for i in range(0, len(bits) - 7, 8))
        try:
            cand = raw.decode("ascii")
        except Exception:  # noqa: BLE001
            continue
        m = TRACE_NO_RE.search(cand)
        if m:
            return m.group(0)
    m = TRACE_NO_RE.search(text)
    return m.group(0) if m else None


def strip_marks(body: str) -> str:
    """Strip labels added by this module -- the explicit label line + zero-width watermark.

    Regeneration / edit-and-save both re-label; without stripping first, labels would stack layer upon layer.
    """
    if not body:
        return ""
    out = _ZW_BLOCK_RE.sub("", body)
    # Remove the explicit label block entirely: optional preceding separator + the `> 内容由AI生成…` ("AI-generated content...") line.
    # Swallow preceding blank lines too, so repeated regeneration does not accumulate a run of blank lines at the end of the body.
    out = _DISCLOSURE_BLOCK_RE.sub("", out)
    return out.rstrip()


def outbound_body(body: str) -> str:
    """**Unified pass at publish exits** -- labels are always stripped from bodies posted externally.

    New drafts carry no labels from generation (`stamp`'s `mark_body` is off by default), but legacy drafts, bodies pasted in
    from elsewhere, and any future accidental enabling of labeling could all get the "内容由AI生成…生成方 …" ("AI-generated content... generated by ...")
    line published verbatim by the platform. So this runs wherever **every external push point** (aitoearn / Ruanwenjiang /
    Meijieku / Mediumsly) reads the body, without relying on the DB data always being clean.

    When adding a new external publish channel, the body must be read through this function, not directly from `doc.body_markdown`.
    """
    return strip_marks(body or "")


def disclosure_line(trace_no: str) -> str:
    """Explicit label line -- the section at the end of the body."""
    return (f"\n\n---\n\n> {DISCLOSURE_TEXT}｜内容编号 {trace_no}"
            f"｜生成方 {SUBJECT_NAME}")


def apply_marks(body: str, trace_no: str) -> str:
    """Add the explicit label + implicit watermark to the body. **Idempotent** -- strips old labels before adding new ones."""
    clean = strip_marks(body or "")
    if not clean.strip():
        return clean
    return clean + disclosure_line(trace_no) + encode_watermark(trace_no)


# --------------------------- Persistence ---------------------------
def is_ai_generated(doc) -> bool:
    """User-supplied drafts (source='user') are not AI-generated; labeling them as AI would be false labeling, so never label them."""
    return (getattr(doc, "source", None) or "ai") == "ai"


def stamp(db, doc, *, mark_body: bool = False) -> bool:
    """Write the three provenance columns and label the body as needed. Returns whether anything changed (the caller decides when to commit).

    **Must be called after the doc has a primary key** (the id includes doc.id); flushes first if there is none.
    All three columns are written only when empty -- regeneration does not change the owner or first-generation IP,
    otherwise the provenance ledger would be falsely overwritten by later regenerations.

    Since 2026-08-17 `mark_body` is off by default: the body no longer keeps the explicit label line or zero-width watermark,
    and every stamp also strips old labels from legacy bodies. The three provenance columns are still written,
    so the ledger and lookup by id are unaffected; to restore body labeling, pass `mark_body=True` explicitly.
    """
    try:
        if getattr(doc, "id", None) is None:
            db.flush()
        changed = False
        origin = current_origin()

        if not getattr(doc, "gen_trace_no", None):
            doc.gen_trace_no = make_trace_no(doc.id, doc.created_at)
            changed = True
        if getattr(doc, "gen_user_id", None) is None:
            doc.gen_user_id = origin.user_id or _topic_owner_id(db, doc)
            changed = True
        if not getattr(doc, "gen_client_ip", None):
            doc.gen_client_ip = origin.client_ip or SYSTEM_IP
            changed = True

        body = doc.body_markdown or ""
        if mark_body and is_ai_generated(doc):
            marked = apply_marks(body, doc.gen_trace_no)
        else:
            # When not labeling, actively strip -- washing away old label lines + zero-width watermarks in legacy bodies
            marked = strip_marks(body)
        if marked != body:
            doc.body_markdown = marked
            changed = True
        return changed
    except Exception as e:  # noqa: BLE001
        # A labeling failure must not roll back the whole generation batch -- the draft remains, labeling can be rerun later
        log.warning("content_marking.stamp failed for doc=%s: %s",
                    getattr(doc, "id", "?"), e)
        return False


def stamp_many(db, docs) -> int:
    """Label in bulk, returning the number changed. The caller is responsible for commit."""
    n = 0
    for d in docs or []:
        if stamp(db, d):
            n += 1
    return n


def _topic_owner_id(db, doc) -> Optional[int]:
    """Owner fallback: automated batch runs have no trigger user, so record the topic owner (the content was indeed generated for them)."""
    try:
        from geo.models.ai_telemetry import AiTelemetryTopicORM

        t = db.get(AiTelemetryTopicORM, doc.topic_id)
        return getattr(t, "user_id", None) if t else None
    except Exception:  # noqa: BLE001
        return None
