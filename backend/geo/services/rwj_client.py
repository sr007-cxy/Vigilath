"""HTTP client for the Meijieku-family publishing platforms (Ruanwenjiang + Meijieku, two sites on the same backend).

**Why one client serves both**: Ruanwenjiang's API domain is literally `tenant.meijieku.com` --
it's a tenant site of Meijieku (`vip.meijieku.com` / `api.meijieku.com`). The protocols are 99%
identical (same JWT shape, same business codes, same resource/draft/order request bodies); only route
spelling differs, so the differences are folded into `SiteSpec` and the rest of the code is shared:

    provider  site            API base                        resource list route
    rwj       Ruanwenjiang    https://tenant.meijieku.com/api  /Resource.{Type}/list
    mjk       Meijieku        https://api.meijieku.com         /Resource/{Type}/list

Three other measured differences: login/renewal/user-info route casing differs (`/member/*` vs
`/Member/*`), the init endpoint name differs (`/Base/init` vs `/System/init`), and getInfo
is GET on one and POST on the other. Everything else (`/Draft/save|list|delete`, business codes 200/103/402/411,
token 2h + refreshToken 7d, the injection surface of `sort` spliced straight into SQL) is identical on both.

Ported into backend from tmp/ruanwenjiang/rwj/client.py, fixing two errors in the early version per the measured conclusions
in docs/03-系统设计/内容与发布/发文对接.md:

  1. `price_type` is an **array** of placement methods `[{label, value, prefix, disabled}]`,
     not a prefix string -- the early version's `prefix = res["price_type"]` built field names that were
     invalid keys. Now `delivery_options()` / `pick_delivery()`: first pick a
     non-disabled placement method, use its `prefix` to build `{prefix}{level}` for the price, and put
     its `value` into the payload's `resource[].type`.
  2. The `sort` parameter is spliced straight into SQL ORDER BY server-side (passing `price asc` throws
     `Unknown column 'price'`; it's an injection surface) -- only whitelisted values generated by `sort_expr()`
     are allowed here; external input is never passed through.

Other protocol notes (all measured):
  - Authorization carries the raw JWT, **without** a `Bearer ` prefix; new X-Request-Id per request
  - Expired login session shows as business code 103 (HTTP still 200); token 2h / refreshToken 7d,
    renewal must replace both; request() auto-renews and retries once on hit
  - List endpoints must send the full set of empty filter fields (FILTER_FIELDS), otherwise total is wrong
  - There's no parameter to query by resource_id; only fuzzy title + paging
  - /Article.{Type}/add really charges and **has no server-side idempotency**; /Draft/save is free, doesn't validate
    the body, creates a new one every time; there's no /Draft/info (list returns full content directly)
  - getInfo returns the unmasked phone number -- pass through mask_mobile() before any logging/passthrough

Config comes from geo.database.settings (two isomorphic variable groups RWJ_* / MJK_*); in-process singleton
get_client(provider), one per provider, with login/refresh serialized by a lock.
Synchronous httpx.Client: call sites are all sync def endpoints (FastAPI runs them in a thread pool), same stack as sync
SQLAlchemy; low-frequency ops actions don't need async.
"""
