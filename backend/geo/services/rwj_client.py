@dataclass(frozen=True)
class SiteSpec:
    """Integration spec of one publishing site -- all differences between the two live here; don't scatter them to callers."""
    provider: str            # rwj | mjk, used by task channel_meta / provider column of the resource mirror
    label: str               # Chinese site name, goes directly into the task table platform column and frontend copy
    default_base_url: str
    origin: str              # the platform validates Origin/Referer; must be the member site, not the API domain
    login_path: str
    refresh_path: str
    info_path: str
    info_method: str         # Ruanwenjiang GET / Meijieku POST, measured; wrong one gives 404
    init_path: str
    resource_list: str       # resource list route template, {t} = resource type name
    article_list: str
    article_add: str
    article_info: str        # query a single order directly by article_id (no paging)
    article_appeal: str      # file after-sales (link broken / content deleted -> platform refunds)
    upload_path: str         # editor attachment upload (images use ?action=image)
    filter_fields: dict[str, tuple[str, ...]]   # filter fields each type's list endpoint actually accepts

    def path(self, template: str, type_: str) -> str:
        if type_ not in self.filter_fields:
            raise RwjApiError(f"unknown type: {type_}")
        return template.format(t=type_)


