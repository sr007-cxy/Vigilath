def site(provider: str) -> SiteSpec:
    spec = SITES.get((provider or DEFAULT_PROVIDER).strip().lower())
    if spec is None:
        raise RwjApiError(f"unknown provider {provider!r}")
    return spec


def filter_fields(provider: str, type_: str) -> tuple[str, ...]:
    """Valid filter fields for a site and type -- endpoints use it as a key allowlist; don't reference the module-level FILTER_FIELDS anymore."""
    fields = site(provider).filter_fields.get(type_)
    if fields is None:
        raise RwjApiError(f"unknown type: {type_}")
    return fields


class RwjApiError(RuntimeError):
    def __init__(self, message: str, *, status: Any = None, payload: Any = None):
        super().__init__(message)
        self.status = status
        self.payload = payload


class RwjAuthError(RwjApiError):
    """Token missing/expired (business code 103 etc.); request() first auto-renews and retries once."""


def mask_mobile(mobile: str) -> str:
    """Phone number masking: keep first 3 and last 2. getInfo returns the full number; must pass through here before leaving the client."""
    m = str(mobile or "")
    if len(m) < 7:
        return "*" * len(m)
    return m[:3] + "*" * (len(m) - 5) + m[-2:]


def sort_expr(key: str, level: int) -> str:
    """Map a sort enum name to a sort string the server understands (allowlist, prevents ORDER BY injection).

    Sort fields must carry the level suffix (`price_1 asc`); `price asc` makes the server report
    Unknown column. level accepts only 1/2/3.
    """
    lv = int(level)
    if lv not in (1, 2, 3):
        raise RwjApiError(f"invalid level {level!r}")
    table = {
        "price_asc": f"price_{lv} asc",
        "price_desc": f"price_{lv} desc",
        "rate_desc": "publish_rate desc",   # publish rate first (measured working)
        "weigh_desc": "pc_weigh desc",      # desktop weight first (measured working)
    }
    if key not in table:
        raise RwjApiError(f"unsupported sort {key!r}")
    return table[key]


# ---------- Placement method / price (fixes the early version's price_type prefix-string bug) ----------

def delivery_options(res: dict) -> list[dict]:
    """Available placement methods for a resource. price_type missing/empty -> default direct publish (prefix=price_, value=None)."""
    pt = res.get("price_type")
    if not pt or not isinstance(pt, list):
        return [{"label": "直发", "value": None, "prefix": "price_", "disabled": False}]
    return [o for o in pt if isinstance(o, dict) and not o.get("disabled")]


def pick_delivery(res: dict, value: Any = None) -> dict:
    """Choose a placement method: default is the first available; with an explicit value, verify it exists and isn't disabled."""
    opts = delivery_options(res)
    if not opts:
        raise RwjApiError(
            f"resource {res.get('resource_id')} has no enabled delivery option")
    if value is None:
        return opts[0]
    for o in opts:
        if o.get("value") == value:
            return o
    raise RwjApiError(
        f"delivery value {value!r} not available on resource {res.get('resource_id')}")


def resource_price(res: dict, level: int, *, delivery: Optional[dict] = None,
                   answer_count: Optional[int] = None) -> str:
    """Get the displayed price by membership level (+ placement method / answer count) (API doc 4.5)."""
    if answer_count is not None:  # Q&A: price_{answerCount}_{level}
        key = f"price_{answer_count}_{level}"
    else:
        prefix = (delivery or pick_delivery(res)).get("prefix") or "price_"
        key = f"{prefix}{level}"
    if key not in res:
        raise RwjApiError(
            f"price field {key!r} missing on resource {res.get('resource_id')}")
    return res[key]


@dataclass
class Tokens:
    token: str = ""
    refresh_token: str = ""

    @classmethod
    def load(cls, path: Path) -> "Tokens":
        if not path.exists():
            return cls()
        try:
            raw = json.loads(path.read_text())
        except (ValueError, OSError):
            return cls()
        return cls(token=raw.get("token", ""), refresh_token=raw.get("refreshToken", ""))

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({"token": self.token, "refreshToken": self.refresh_token}))
        path.chmod(0o600)


@dataclass
class RwjClient:
    mobile: str = ""
    password: str = ""
    base_url: str = ""          # empty = use spec.default_base_url
    token_path: Path = field(default_factory=lambda: Path("data/rwj_tokens.json"))
    timeout: float = 30.0
    spec: SiteSpec = RWJ_SITE
    _tokens: Tokens = field(init=False)
    _http: httpx.Client = field(init=False)
    _auth_lock: threading.Lock = field(init=False, default_factory=threading.Lock)

    def __post_init__(self) -> None:
        self.base_url = self.base_url or self.spec.default_base_url
        self._tokens = Tokens.load(self.token_path)
        # trust_env=False: Meijieku/Ruanwenjiang are both CN domains and must be reached directly. geo-backend on the test host sets
        # HTTP(S)_PROXY (the SS egress used for overseas engines); httpx reads env vars by default and would throw these two onto
        # the US egress machine, showing up as "ssl.c:990: The handshake operation timed out".
        self._http = httpx.Client(base_url=self.base_url, timeout=self.timeout, trust_env=False)

    @property
    def configured(self) -> bool:
        return bool(self.mobile and self.password)

    @property
    def provider(self) -> str:
        return self.spec.provider

    # ---------- Low-level requests ----------

    def _headers(self, *, auth: bool = True) -> dict[str, str]:
        origin = self.spec.origin
        h = {
            "Accept": "application/json, text/plain, */*",
            "Content-Type": "application/json",
            "X-Request-Id": uuid.uuid4().hex[:21],
            "Origin": origin,
            "Referer": origin + "/",
        }
        if auth:
            if not self._tokens.token:
                raise RwjAuthError("no access token; call login() first")
            h["Authorization"] = self._tokens.token
        return h

    def _raw(self, method: str, path: str, *, json_body: Any = None, auth: bool = True) -> dict:
        resp = self._http.request(method, path, json=json_body, headers=self._headers(auth=auth))
        try:
            data = resp.json()
        except ValueError:
            raise RwjApiError(f"{path}: non-JSON response (HTTP {resp.status_code})",
                              status=resp.status_code, payload=resp.text[:500])

        status = data.get("status")
        if status == 200 or (status is None and resp.status_code == 200 and "data" in data):
            return data
        # 103 = "请登录后重试!" ("please log in and retry", no token); 402 = "token过期" ("token expired") (measured, HTTP still 200)
        if resp.status_code in (401, 403) or status in (103, 402, 401, 403, 4001, 10001):
            raise RwjAuthError(str(data.get("msg") or data.get("message") or "auth expired"),
                               status=status, payload=data)
        raise RwjApiError(str(data.get("msg") or data.get("message") or data),
                          status=status, payload=data)

    def request(self, method: str, path: str, *, json_body: Any = None, auth: bool = True) -> dict:
        """Request with one automatic renew-and-retry."""
        try:
            return self._raw(method, path, json_body=json_body, auth=auth)
        except RwjAuthError:
            if not auth:
                raise
            self.refresh_or_login()
            return self._raw(method, path, json_body=json_body, auth=auth)

    # ---------- Login (singleton shared across threads, renewal serialized by a lock) ----------

    def login(self) -> Tokens:
        if not self.configured:
            raise RwjApiError("RWJ_MOBILE / RWJ_PASSWORD not configured")
        with self._auth_lock:
            data = self._raw("POST", self.spec.login_path,
                             json_body={"mobile": self.mobile, "password": self.password},
                             auth=False)["data"]
            self._tokens = Tokens(token=data["token"], refresh_token=data["refreshToken"])
            self._tokens.save(self.token_path)
            return self._tokens

    def refresh(self) -> Tokens:
        with self._auth_lock:
            if not self._tokens.refresh_token:
                raise RwjAuthError("no refresh token")
            data = self._raw("POST", self.spec.refresh_path,
                             json_body={"refreshToken": self._tokens.refresh_token},
                             auth=False)["data"]
            # API doc 3.2: both tokens must be replaced
            self._tokens = Tokens(token=data["token"], refresh_token=data["refreshToken"])
            self._tokens.save(self.token_path)
            return self._tokens

    def refresh_or_login(self) -> Tokens:
        try:
            return self.refresh()
        except (RwjApiError, KeyError):
            return self.login()

    def ensure_session(self) -> dict:
        """Ensure a usable session; returns getInfo's data (includes the unmasked phone number; don't pass it out directly)."""
        if not self._tokens.token:
            self.login()
        try:
            return self.get_info()
        except RwjAuthError:
            self.refresh_or_login()
            return self.get_info()

    def get_info(self) -> dict:
        # Ruanwenjiang is GET, Meijieku is POST (measured; the wrong one gives a webman 404)
        method = self.spec.info_method
        body = {} if method == "POST" else None
        return self._raw(method, self.spec.info_path, json_body=body)["data"]

    # ---------- Resource list ----------

    def default_list_body(self, type_: str, **overrides: Any) -> dict:
        fields = self.spec.filter_fields.get(type_)
        if fields is None:
            raise RwjApiError(f"unknown type: {type_}")
        body: dict[str, Any] = {f: "" for f in fields}
        body.update({f: "" for f in COMMON_FIELDS})
        body.update({"pageNo": 1, "pageSize": 20})
        body.update(overrides)
        return body

    def list_resources(self, type_: str, **overrides: Any) -> dict:
        body = self.default_list_body(type_, **overrides)
        path = self.spec.path(self.spec.resource_list, type_)
        return self.request("POST", path, json_body=body)["data"]

    def base_init(self) -> dict:
        """Page init data. `data.field.{website|wemedia|...}.field_N` holds each business type's
        filter dimension options ([{field_id, field_title, ...}]); list filters pass values by field_id.
        Note: Ruanwenjiang's /Base/init response has no status field (_raw handles it); Meijieku's
        /System/init does; both can go through the same path."""
        return self.request("POST", self.spec.init_path, json_body={}).get("data") or {}

    def find_resource(self, type_: str, resource_id: int, title_hint: str,
                      *, max_pages: int = 5) -> Optional[dict]:
        """Locate one resource by (resource_id, name keyword).

        The list endpoint has no id lookup parameter, only fuzzy title + paging; with an empty title_hint
        paging the whole table is pointless, so return None for the caller to handle.
        """
        hint = (title_hint or "").strip()
        if not hint:
            return None
        for page in range(1, max_pages + 1):
            data = self.list_resources(type_, title=hint, pageNo=page, pageSize=50)
            rows = data.get("data") or []
            for r in rows:
                if r.get("resource_id") == resource_id:
                    return r
            if not rows or page >= int(data.get("last_page") or 1):
                return None
        return None

    # ---------- Drafts (free; path has no .{Type}, type is carried by lowercase type in body) ----------

    def draft_save(self, body: dict) -> Any:
        return self.request("POST", "/Draft/save", json_body=body).get("data")

    def draft_list(self, type_: str, **overrides: Any) -> Any:
        body = {"type": type_.lower(), "pageNo": 1, "pageSize": 20}
        body.update(overrides)
        return self.request("POST", "/Draft/list", json_body=body).get("data")

    def draft_delete(self, draft_id: int) -> Any:
        return self.request("POST", "/Draft/delete", json_body={"draft_id": draft_id}).get("data")

    # ---------- Payload assembly / formal publish (charged) ----------

    def build_publish_body(self, type_: str, *, title: str, content: str,
                           resources: list[dict], level: int,
                           remark: str = "", customer: str = "",
                           out_order_no: str = "") -> dict:
        """Assemble the Article.{Type}/add request body (Website shape; publish and draft are isomorphic).

        resource[].type gets the placement method's value (fixes the early version hardcoding None).
        """
        items = []
        for r in resources:
            d = pick_delivery(r)
            items.append({
                "resource_id": r["resource_id"],
                "name": r["title"],
                "price": resource_price(r, level, delivery=d),
                "title": "",
                "type": d.get("value"),
            })
        body = {
            "title_type": 1,
            "title": title,
            "resource": items,
            "content": content,
            "remark": remark,
            "customer": customer,
        }
        # Downstream order number -- the platform supports idempotency since v1.1 (API 2 in the "downstream agent API integration doc"):
        # resubmitting the same out_order_no under the same account returns the first order and **doesn't charge again**,
        # with idempotent:true in the response. Timeout retries rely on this as the fallback; always pass it when possible.
        if out_order_no:
            body["out_order_no"] = str(out_order_no)[:64]
        if type_ == "Wemedia":
            body["account_rule"] = 3   # 3 = account swap not allowed (default, most conservative)
        return body

    def build_draft_body(self, type_: str, **kwargs: Any) -> dict:
        body = self.build_publish_body(type_, **kwargs)
        return {"type": type_.lower(), **body}

    def publish(self, type_: str, body: dict) -> dict:
        """Formal publish -- creates an order and charges. **No server-side idempotency**; the caller handles dedupe."""
        return self.request("POST", self.spec.path(self.spec.article_add, type_), json_body=body)

    def articles(self, type_: str, **overrides: Any) -> dict:
        """Article/order list.

        Besides paging it also accepts `order_id` (exact), `title` / `resource_title` (fuzzy),
        `customer`, `status`, `create_time` / `release_time` ranges -- see
        API 3 in the "downstream agent API integration doc". **With an order number, don't page to find it**.
        """
        body = {"pageNo": 1, "pageSize": 20}
        body.update(overrides)
        path = self.spec.path(self.spec.article_list, type_)
        return self.request("POST", path, json_body=body)["data"]

    def order_query(self, type_: str, out_order_nos: list[str] | str) -> list[dict]:
        """Reverse-lookup our articles by **downstream order number** (API 5, up to 20 per call).

        type_ uses lowercase enums (website/wemedia/shortvideo/ghostwrite/question);
        numbers not found are silently ignored, neither erroring nor taking a slot.
        """
        nos = [out_order_nos] if isinstance(out_order_nos, str) else list(out_order_nos)
        nos = [str(n)[:64] for n in nos if n][:20]
        if not nos:
            return []
        data = self.request("POST", "/Article/OrderQuery/outOrder", json_body={
            "type": type_.lower(), "out_order_no": ",".join(nos),
        })
        rows = data.get("result")
        return [r for r in rows if isinstance(r, dict)] if isinstance(rows, list) else []

    def article_info(self, type_: str, article_id: int) -> dict:
        """Query one order directly by article_id (includes the body archived on the platform side, used as the liveness check baseline)."""
        path = self.spec.path(self.spec.article_info, type_)
        return self.request("POST", path, json_body={"article_id": int(article_id)})["data"]

    # Reason allowlist from the platform's "apply for after-sales" dialog (copied from the member site; custom wording isn't accepted)
    APPEAL_REASONS = (
        "时效内打不开链接",
        "链接错误，无法打开",
        "内容被删",
        "回答被删",
        "提问被删",
        "未收录，申请退款(包收录资源)",
        "发布（账号）结果与案例不一致",
        "内容填写错误",
        "其他原因",
    )

    def appeal(self, type_: str, *, article_id: int, title: str, info: str) -> Any:
        """Apply for after-sales (platform refunds once accepted). title must be verbatim from APPEAL_REASONS.

        **External action that affects account reputation**: the caller must guard the gate and idempotency itself; this only sends the request.
        """
        if title not in self.APPEAL_REASONS:
            raise RwjApiError(f"售后原因不在平台白名单里: {title!r}")
        path = self.spec.path(self.spec.article_appeal, type_)
        return self.request("POST", path, json_body={
            "article_id": int(article_id), "title": title, "info": info,
        }).get("data")

    def upload_image(self, data: bytes, filename: str,
                     content_type: str = "image/png") -> str:
        """Upload an image to the platform's own object storage; returns the absolute URL it gives back.

        **Why it must be uploaded**: if body images still point at our own domain, once the media
        publishes it they're broken external links (our `/api/ai-telemetry/public/topic-media/...`
        isn't reachable from the internet). The platform member site's editor does exactly this -- uploads via the UEditor protocol to
        `oss.meijieku.com`, leaving only platform URLs in the body.

        Protocol (measured 2026-08-21, matches the member site frontend):
          POST {base}/Ueditor/handle?action=image, multipart field name `file`
          → {"state":"SUCCESS","url":"https://oss.meijieku.com/uploads/api/…"}
        Field and action names aren't guesses; they come from `?action=config`'s
        imageActionName=image / imageFieldName=file; allows png/jpg/jpeg/gif/bmp,
        max 50MB per image.
        """
        def _post() -> dict:
            h = self._headers()
            h.pop("Content-Type", None)          # let httpx generate the multipart boundary
            resp = self._http.post(self.spec.upload_path, params={"action": "image"},
                                   files={"file": (filename, data, content_type)},
                                   headers=h)
            try:
                return resp.json()
            except ValueError:
                raise RwjApiError(f"图片上传返回非 JSON(HTTP {resp.status_code})",
                                  status=resp.status_code, payload=resp.text[:300])

        try:
            out = _post()
        except RwjAuthError:
            self.refresh_or_login()
            out = _post()
        state = str(out.get("state") or "")
        url = str(out.get("url") or "")
        if state.upper() != "SUCCESS" or not url:
            # UEditor reports errors via state (e.g. 「文件大小超出」 ("file size exceeded"), 「不允许的文件类型」 ("file type not allowed"))
            raise RwjApiError(f"图片上传失败: {state or out}", payload=out)
        return url

    def aftersales(self, type_: str = "Website", *, status: Any = "all",
                   **overrides: Any) -> dict:
        """After-sales ticket list (neither site's route includes the type). status/resource_type are required; missing one
        makes the server return `Undefined array key`; type=1 refund / 2 replacement link / 3 revision,
        status=0 pending / 1 approved / 2 rejected."""
        body = {"pageNo": 1, "pageSize": 20, "status": status,
                "resource_type": type_.lower()}
        body.update(overrides)
        return self.request("POST", "/Aftersales/list", json_body=body)["data"]

    def close(self) -> None:
        self._http.close()


# ---------- In-process singletons (one per provider) ----------

_clients: dict[str, RwjClient] = {}
_client_lock = threading.Lock()

# provider -> (settings prefix). The two variable groups are isomorphic; don't put any logic here beyond the concrete names.
_SETTINGS_PREFIX = {"rwj": "RWJ", "mjk": "MJK"}


def credentials(provider: str) -> tuple[str, str, str, str]:
    """(mobile, password, api_base, token_path) -- sync jobs that open their own client also go through here."""
    from geo.database import settings

    spec = site(provider)
    p = _SETTINGS_PREFIX[spec.provider]
    return (
        getattr(settings, f"{p}_MOBILE", "") or "",
        getattr(settings, f"{p}_PASSWORD", "") or "",
        getattr(settings, f"{p}_API_BASE", "") or spec.default_base_url,
        getattr(settings, f"{p}_TOKEN_PATH", "") or f"data/{spec.provider}_tokens.json",
    )


def get_client(provider: str = DEFAULT_PROVIDER) -> RwjClient:
    """Build the in-process singleton from settings. Returns an instance even if credentials aren't configured (configured=False);
    the caller (publisher) decides whether to raise RwjNotConfigured."""
    spec = site(provider)
    c = _clients.get(spec.provider)
    if c is None:
        with _client_lock:
            c = _clients.get(spec.provider)
            if c is None:
                mobile, password, api_base, token_path = credentials(spec.provider)
                c = RwjClient(mobile=mobile, password=password, base_url=api_base,
                              token_path=Path(token_path), spec=spec)
                _clients[spec.provider] = c
    return c


def reset_client(provider: Optional[str] = None) -> None:
    """For tests: clear singletons (all if no provider given)."""
    with _client_lock:
        keys = [site(provider).provider] if provider else list(_clients)
        for k in keys:
            c = _clients.pop(k, None)
            if c is not None:
                c.close()
