#!/usr/bin/env bash
# Vigilath GEO skill one-line installer - drop-in for the other party's agent (OpenClaw).
#
#   # No token (recommended): the terminal shows a pairing code; approve with one click in the browser
#   curl -fsSL https://vigilath.cn/skill/install.sh | bash
#
#   # Install only some narrow skills (all 7 narrow skills are installed by default)
#   curl -fsSL https://vigilath.cn/skill/install.sh | bash -s -- --skills site-audit,seo-audit
#   # Install the fallback all-in-one package (for hosts that only accept one skill at a time)
#   curl -fsSL https://vigilath.cn/skill/install.sh | bash -s -- --skills geo
#
#   # Already have a token (old way, still supported)
#   curl -fsSL https://vigilath.cn/skill/install.sh | bash -s -- <your-token> --base https://vigilath.cn
#
# Does three things: 1) copy the skill into the detected skills directories (can install for multiple platforms at once);
#           2) obtain a token and write it to ~/.vigilath/config (chmod 600); 3) self-check.
# Framework-agnostic: auto-detects OpenClaw / Claude / .agents / the current project; --dir or VIGILATH_SKILLS_DIR can also specify it.
#
# ★ --base is the key to "point at whichever domain you installed from": when this script runs via a `curl | bash` pipe,
#   it cannot get its own download URL ($0 is just "bash"), so the base can only be passed in or use the default below.
#   The command generated by the console's "Integrations" page automatically includes --base <current site origin>,
#   so test / vigilath.cn / www.vigilath.cn / www.vigilath.com.cn all line up automatically.
set -euo pipefail

# Default base: the ICP-filed CN domain. Only a fallback when neither --base nor the environment variable is set.
SKILL_BASE="${VIGILATH_SKILL_BASE:-https://vigilath.cn/skill}"   # skill file hosting address
TOKEN=""
SKILLS_DIR="${VIGILATH_SKILLS_DIR:-}"
# The eight narrow skills = the default set. **Excludes the fallback all-in-one package vigilath-geo** -
# its triggers cover all seven scenarios, and installing it alongside the narrow skills confuses the host agent's selection; pick one or the other.
NARROW="site-audit seo-audit mention report radar content weekly sentinel"
WANT=""
# auto = finish after installing and only print one line "run login to connect your account"; force = run device code authorization after installing.
# Defaulting to auto is deliberate: this command is mainly run by the **host agent** (see the install instructions at /skill),
# where stdout is a pipe and nobody is watching, so a 600-second blocking poll will certainly time out - and since copying happened after
# authorization, a timeout meant not a single skill got installed. The promise of the three no-login capabilities (see skills/README.md)
# simply could not be kept in that setup.
AUTH_MODE="auto"

while [ $# -gt 0 ]; do
  case "$1" in
    --dir)   SKILLS_DIR="$2"; shift 2 ;;
    --token) TOKEN="$2"; shift 2 ;;
    # --base accepts values with or without the /skill suffix, normalized to <origin>/skill
    --base)  SKILL_BASE="${2%/}"; SKILL_BASE="${SKILL_BASE%/skill}/skill"; shift 2 ;;
    # --skills all|geo|<comma-separated short names>; omitted = the eight narrow skills
    --skills) WANT="$(printf '%s' "$2" | tr ',' ' ')"; shift 2 ;;
    # Connect the account after installing (the command generated by the console's "Integrations" page includes this)
    --login) AUTH_MODE="force"; shift ;;
    # Only the no-login capabilities. --no-auth is an alias - skills/README.md says "authorization can be skipped"
    --no-login|--no-auth) AUTH_MODE="skip"; shift ;;
    -*) echo "未知参数:$1" >&2; exit 2 ;;
    *) [ -z "$TOKEN" ] && TOKEN="$1"; shift ;;
  esac
done

say() { printf '\033[36m[vigilath-geo]\033[0m %s\n' "$*"; }
die() { printf '\033[31m[vigilath-geo] 错误:%s\033[0m\n' "$*" >&2; exit 1; }
warn() { printf '\033[33m[vigilath-geo] %s\033[0m\n' "$*" >&2; }

command -v python3 >/dev/null 2>&1 || die "需要 python3(skill 客户端纯标准库,无三方依赖)"
command -v curl    >/dev/null 2>&1 || die "需要 curl"

API_BASE="${SKILL_BASE%/skill}/api/agent/v1"

# ── 1) No token given: use device code authorization; the terminal shows a code, a person approves in the browser ────────────────────
# Benefit: the token never goes through the clipboard or into shell history, and the website can print the same parameterless command.
device_login() {
  local resp status
  resp="$(curl -fsS -m 20 -X POST "$API_BASE/device/code" \
            -H 'Content-Type: application/json' \
            -d "{\"client\":\"$(hostname 2>/dev/null || echo cli)\"}" 2>/dev/null)" \
    || { warn "连不上 $API_BASE —— 检查网络,或用 --base 指定正确的站点域名"; return 1; }

  # Parse with python3 and emit shell assignments (all values go through shlex.quote, safe with special characters)
  eval "$(printf '%s' "$resp" | python3 -c '
import json, shlex, sys
try:
    d = json.load(sys.stdin)
except Exception:
    print("DEV_STATUS=" + shlex.quote("parse_error")); sys.exit(0)
for k in ("status", "device_code", "user_code", "verify_url", "verify_url_complete", "interval", "expires_in"):
    print("DEV_" + k.upper() + "=" + shlex.quote(str(d.get(k, ""))))
')"
  [ "${DEV_STATUS:-}" = "ok" ] || { warn "起授权流程失败(服务端返回:${DEV_STATUS:-空})"; return 1; }

  # Write the link and pairing code to **both stdout and stderr**. Under `curl | bash` stdout is a pipe and
  # fully buffered by default, so the pairing code may be held in the buffer until the 10-minute timeout - the user waits
  # until it expires without ever seeing the code. stderr is unbuffered; writing both ensures the host agent sees it whichever stream it reads.
  # (geo_client.py:login solves this with sys.stdout.reconfigure(line_buffering=True);
  #  the shell has no equivalent.)
  _emit() { printf "$@"; printf "$@" >&2; }
  printf '\n'
  say "请在浏览器完成授权(10 分钟内有效):"
  _emit '\n    打开:\033[4m%s\033[0m\n' "${DEV_VERIFY_URL_COMPLETE:-$DEV_VERIFY_URL}"
  _emit '    配对码:\033[1;33m%s\033[0m\n\n' "$DEV_USER_CODE"
  say "等待批准中…(在浏览器点「批准」后这里会自动继续)"

  local interval="${DEV_INTERVAL:-5}" deadline out st
  deadline=$(( $(date +%s) + ${DEV_EXPIRES_IN:-600} ))
  while [ "$(date +%s)" -lt "$deadline" ]; do
    sleep "$interval"
    # A failed poll (network blip) should not abort the whole flow; swallow the error and keep waiting
    out="$(curl -fsS -m 20 -X POST "$API_BASE/device/token" \
             -H 'Content-Type: application/json' \
             -d "{\"device_code\":\"$DEV_DEVICE_CODE\"}" 2>/dev/null || true)"
    [ -n "$out" ] || continue
    eval "$(printf '%s' "$out" | python3 -c '
import json, shlex, sys
try:
    d = json.load(sys.stdin)
except Exception:
    d = {"status": "pending"}
for k in ("status", "token", "message"):
    print("POLL_" + k.upper() + "=" + shlex.quote(str(d.get(k, ""))))
')"
    st="${POLL_STATUS:-pending}"
    case "$st" in
      approved) TOKEN="$POLL_TOKEN"; say "✅ 授权成功"; return 0 ;;
      pending|slow_down) : ;;
      denied)   warn "${POLL_MESSAGE:-用户拒绝了本次授权}"; return 1 ;;
      expired)  warn "${POLL_MESSAGE:-配对码已过期}"; return 1 ;;
      *) : ;;
    esac
  done
  warn "等待授权超时(10 分钟)"
  return 1
}


# ── 2) Detect skills directories ───────────────────────────────────────────────────────
# When --dir / the environment variable is given, install only there; otherwise install into **all** existing agent skills directories,
# so that multiple agents on the same machine (OpenClaw + Claude Code ...) can all discover this skill.
DESTS=()
if [ -n "$SKILLS_DIR" ]; then
  DESTS+=("$SKILLS_DIR")
else
  [ -d "$HOME/.openclaw/skills" ] && DESTS+=("$HOME/.openclaw/skills")          # OpenClaw global
  [ -d "$HOME/.claude/skills" ]   && DESTS+=("$HOME/.claude/skills")            # Claude Code global
  [ -d "$HOME/.agents/skills" ]   && DESTS+=("$HOME/.agents/skills")            # generic personal agent directory
  # Current project workspace (OpenClaw's <workspace>/skills looks like this).
  # ★ But exclude the case where "this is the skill source repo itself" - running the installer at the repo root
  #   would write install output (client copies) back into the source directory and pollute the git working tree. Hit on 2026-08-19.
  if [ -d "./skills" ] && [ ! -f "./skills/vigilath-geo/install.sh" ]; then
    DESTS+=("$(pwd)/skills")
  fi
  [ ${#DESTS[@]} -eq 0 ] && DESTS+=("$HOME/.vigilath/skills")                   # fallback when none exist
fi

# Decide which skills to install. Short name -> directory name vigilath-<short name>; `all` = seven narrow skills + the fallback all-in-one package.
case "${WANT:-}" in
  "")    PICK="$NARROW" ;;
  all)   PICK="$NARROW geo" ;;
  *)     PICK="$WANT" ;;
esac

# Download once into a temp directory, then distribute to each skills directory (avoids repeated downloads).
# The client has **a single source in the whole repo** (vigilath-geo/scripts/geo_client.py), copied into each skill directory at install time -
# each skill carrying its own copy is the self-containment the skill spec requires, but there is only one source, so they cannot drift apart.
STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT
SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" 2>/dev/null && pwd || true)"
ROOT_DIR="$(cd "$SELF_DIR/.." 2>/dev/null && pwd || true)"   # skills/ root when run directly from a local repo

fetch() { # fetch <path relative to skills/> <target>; use the local file if present, otherwise download
  if [ -n "$ROOT_DIR" ] && [ -f "$ROOT_DIR/$1" ]; then cp "$ROOT_DIR/$1" "$2"; return 0; fi
  # New hosting layout: <base>/<skill directory>/...; the old layout only exposed the all-in-one package, kept for compatibility
  curl -fsSL "$SKILL_BASE/$1" -o "$2" 2>/dev/null && return 0
  curl -fsSL "$SKILL_BASE/${1#vigilath-geo/}" -o "$2" 2>/dev/null && return 0
  return 1
}

fetch "vigilath-geo/scripts/geo_client.py" "$STAGE/geo_client.py" \
  || die "下载客户端失败(基址 $SKILL_BASE)——检查网络或 --base"

FIRST_DEST=""
INSTALLED=""
for name in $PICK; do
  slug="vigilath-${name#vigilath-}"
  if ! fetch "$slug/SKILL.md" "$STAGE/SKILL.md"; then
    warn "跳过 $slug(取不到 SKILL.md,可能是技能名写错了)"
    continue
  fi
  # The all-in-one package also gets a README; narrow skills do not need one
  HAS_README=0
  [ "$slug" = "vigilath-geo" ] && fetch "$slug/README.md" "$STAGE/README.md" && HAS_README=1

  for d in "${DESTS[@]}"; do
    dest="$d/$slug"
    mkdir -p "$dest/scripts"
    cp "$STAGE/SKILL.md" "$dest/SKILL.md"
    [ "$HAS_README" = "1" ] && cp "$STAGE/README.md" "$dest/README.md"
    cp "$STAGE/geo_client.py" "$dest/scripts/geo_client.py"
    [ -z "$FIRST_DEST" ] && FIRST_DEST="$dest"
  done
  INSTALLED="$INSTALLED $slug"
done

[ -n "$INSTALLED" ] || die "一个技能都没装上 —— 检查 --skills 的名字,或基址 $SKILL_BASE 是否可达"
for d in "${DESTS[@]}"; do say "已安装到 $d:$INSTALLED"; done

# ── 3) Write config (the base shares the origin of the host the skill was downloaded from, auto-aligning test/prod) ────────────
#
# **Must be written once before authorization.** It used to be authorize first, write later, so no-login users had no such file at all,
# and geo_client.py's BASE fell back to the hard-coded vigilath.cn - a client installed from the test site
# would hit production. Without a token only the base is written, not an empty VIGILATH_AGENT_TOKEN= line.
write_config() {
  mkdir -p "$HOME/.vigilath"
  umask 077
  {
    echo "# Vigilath GEO —— 机密,勿提交"
    [ -n "$TOKEN" ] && echo "VIGILATH_AGENT_TOKEN=$TOKEN"
    echo "VIGILATH_BASE=$API_BASE"
  } > "$HOME/.vigilath/config"
  chmod 600 "$HOME/.vigilath/config"
}
write_config
say "配置已写入 ~/.vigilath/config(权限 600,API 基址 $API_BASE)"

# ── 4) Self-check ──────────────────────────────────────────────────────────────────
# The no-login one (check) must work - it is the only capability that does not depend on credentials, so verify it first, then the authorization chain.
say "自检中…"
if python3 "$FIRST_DEST/scripts/geo_client.py" check https://example.com --no-seo >/dev/null 2>&1; then
  say "✅ 免登录检测可用(无需凭证):geo_client.py check <网址>"
else
  warn "免登录检测没跑通 —— 检查网络能否访问 ${API_BASE%/agent/v1}"
fi

# ── 5) Authorization (optional, placed last) ──────────────────────────────────────────────────
# The skills are installed and the no-login capability verified, so this section does not affect the install result whether it succeeds or fails.
LOGIN_CMD="python3 $FIRST_DEST/scripts/geo_client.py login"
if [ -n "$TOKEN" ]; then
  :                                    # given directly via --token, already in the config
elif [ "$AUTH_MODE" = "force" ]; then
  if device_login; then
    write_config                       # got a token, rewrite once
  else
    warn "授权没完成 —— 免登录的三个技能照常可用。想连账号随时跑:"
    warn "  $LOGIN_CMD"
  fi
fi

if [ -n "$TOKEN" ]; then
  if python3 "$FIRST_DEST/scripts/geo_client.py" capabilities >/dev/null 2>&1; then
    say "✅ 授权链路已通。试试:python3 $FIRST_DEST/scripts/geo_client.py chat \"我被搜到几个问题?\""
  else
    warn "已安装,但授权链路未通(token 失效?)。重新授权:$LOGIN_CMD"
  fi
else
  printf '\n'
  say "现在就能用(不需要账号):"
  say "  python3 $FIRST_DEST/scripts/geo_client.py check https://example.com"
  say "  python3 $FIRST_DEST/scripts/geo_client.py mention <品牌> <行业词>"
  printf '\n'
  say "要连你自己的账号(解锁报告 / 监测 / 产稿 / 舆情):"
  say "  $LOGIN_CMD"
fi
